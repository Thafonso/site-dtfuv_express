import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto('http://localhost:4500', { waitUntil: 'networkidle' });
const top = await p.evaluate(() => document.getElementById('aplicacao').getBoundingClientRect().top + scrollY);
const travel = await p.evaluate(() => document.getElementById('aplicacao').offsetHeight - innerHeight);
await p.evaluate(y => window.scrollTo(0, y), Math.round(top + travel * 0.5));
await p.waitForTimeout(700);
await p.screenshot({ path: 'lab/peel/d0-idle.png', clip: { x: 420, y: 180, width: 940, height: 540 } });
const box = await p.locator('.peel__panel').boundingBox();
await p.mouse.move(box.x + box.width * 0.8, box.y + box.height / 2);
await p.mouse.down();
await p.waitForTimeout(300);
await p.screenshot({ path: 'lab/peel/d1-down.png', clip: { x: 420, y: 180, width: 940, height: 540 } });
await p.mouse.move(box.x + box.width * 0.3, box.y + box.height / 2, { steps: 14 });
await p.waitForTimeout(400);
await p.screenshot({ path: 'lab/peel/d2-moved.png', clip: { x: 420, y: 180, width: 940, height: 540 } });
await p.mouse.up();
await p.waitForTimeout(1200);
await p.screenshot({ path: 'lab/peel/d3-released.png', clip: { x: 420, y: 180, width: 940, height: 540 } });
await b.close();
console.log('ok');
